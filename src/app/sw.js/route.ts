import { readdirSync, readFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * The service worker, served from a route rather than sat in public/ so its
 * cache name can carry the build id.
 *
 * The old public/sw.js had CACHE_NAME as a hand-edited constant, and the
 * activate handler deletes every cache that is not it — so that one string was
 * both the version marker and the only thing that purges anything, and keeping
 * it correct meant remembering to edit it on every deploy that touched the
 * shell. That is a rule nobody keeps, and the failure is invisible until
 * somebody is offline holding a stale page.
 *
 * Next writes .next/BUILD_ID on every build and it survives into the
 * standalone output, so reading it here makes the cache name change exactly
 * when the assets it caches change. Nothing to remember.
 */
const BUILD_ID = readBuildId();

function readBuildId(): string {
  for (const path of [
    join(process.cwd(), ".next", "BUILD_ID"),
    join(process.cwd(), ".next", "standalone", ".next", "BUILD_ID"),
  ]) {
    try {
      const id = readFileSync(path, "utf8").trim();
      if (id) return id;
    } catch {
      // Try the next location.
    }
  }
  // `next dev` has no BUILD_ID. A per-process value keeps a dev reload from
  // being served yesterday's cache, and never reaches production.
  return `dev-${Date.now()}`;
}

/**
 * Every file the build put under /_next/static (2.4 MB in 72 files on
 * 2026-11-04), so a new worker can cache all of it at install.
 *
 * Caching chunks only as they were fetched left holes exactly where offline
 * playback needs them. The player loads some code only when it is first used:
 * Vidstack imports its subtitle parser (media-captions) the first time a
 * subtitle is shown. Every deploy empties the cache, so a phone that had not
 * shown a subtitle online since the last deploy had no parser on board, and
 * downloads played on a flight with subtitles switched on and none on screen
 * (Buffy, 2026-11). Which files load late is the bundler's business, so the
 * worker takes them all rather than a list that would go stale.
 */
const STATIC_URLS = listStaticFiles();

function listStaticFiles(): string[] {
  for (const root of [
    join(process.cwd(), ".next", "static"),
    join(process.cwd(), ".next", "standalone", ".next", "static"),
  ]) {
    try {
      return readdirSync(root, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => `/_next/static/${relative(root, join(entry.parentPath, entry.name)).split(sep).join("/")}`);
    } catch {
      // Try the next location.
    }
  }
  // `next dev` serves static files from memory; nothing to list.
  return [];
}

/**
 * Kept as a template string rather than a separate asset so the build id is
 * interpolated once, here, instead of being fetched at runtime by the worker.
 */
function serviceWorkerSource(buildId: string, staticUrls: string[]): string {
  return `// Generated by src/app/sw.js/route.ts — do not edit a copy of this.
// Cache name carries the build id, so a deploy purges the old shell
// automatically and no one has to remember to bump anything.
const CACHE_NAME = ${JSON.stringify(`watch-shell-${buildId}`)};

// /downloads is precached deliberately. Everything else caches only when
// visited, and somebody who taps Download on an item page and then loses
// signal may never have opened the downloads screen — which would make the
// one page they need the one page missing.
const PRECACHE_URLS = [
  "/login",
  "/downloads",
  "/manifest.json",
  "/icon-192.png",
  "/icon-512.png",
];

// Every script, stylesheet and font of this build (see listStaticFiles). Some
// load only when first used, like the subtitle parser, and offline is too
// late to fetch them.
const STATIC_URLS = ${JSON.stringify(staticUrls)};

// One at a time with failures ignored: a chunk that will not come is a gap,
// not a reason to refuse the rest, and a phone on a weak signal should not
// open 70 connections at once.
async function cacheStatic(cache) {
  for (const url of STATIC_URLS) {
    if (await cache.match(url)) continue;
    await cache.add(url).catch(() => {});
  }
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      // addAll is all-or-nothing, which is what we want: a half-populated
      // cache that then becomes the only source offline is worse than none.
      // If it rejects, activate never runs and the old cache stays serving.
      .then((cache) => cache.addAll(PRECACHE_URLS).then(() => cacheStatic(cache)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

// Live state, session state, and video. Caching any of these would either
// serve a stale login or quietly fill the cache with a film — offline
// playback comes from real files on disk, not from here.
// /_watch_offline_/ is a kept-offline film, answered on the device by the app
// shell (OfflineMedia.java). Passing it through here meant fetch() from the
// worker, a 206 offered to the cache, and "Offline 503" for most seeks.
const NEVER_CACHE = [/^\\/jf\\//, /^\\/api\\//, /^\\/watch\\//, /^\\/_watch_offline_\\//];

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  // A Range request is media seeking; a partial response cannot be cached
  // and a worker in the middle only adds a failure point.
  if (request.headers.has("range")) return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (NEVER_CACHE.some((pattern) => pattern.test(url.pathname))) return;

  // Content-hashed and therefore immutable: a changed chunk has a different
  // URL, so cache-first can never go stale here.
  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(
      caches.match(request).then(
        (cached) =>
          cached ||
          fetch(request).then((response) => {
            if (response.ok) {
              const clone = response.clone();
              caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
            }
            return response;
          }),
      ),
    );
    return;
  }

  async function fallback() {
    // Offline, any page opens Downloads: the films kept on the device are
    // all that plays with no connection. Before, the app opened on a saved
    // copy of Home whose Play buttons need the network, and Downloads had
    // to be found in the bottom bar (2026-11-01, at an airport). A redirect,
    // not the page served under another address, so the address is
    // /downloads and that page is the one that runs.
    if (request.mode === "navigate" && url.pathname !== "/downloads" && (await caches.match("/downloads"))) {
      return Response.redirect(new URL("/downloads", self.location.origin).href, 302);
    }
    const cached = await caches.match(request);
    if (cached) return cached;
    // Offline and nothing cached for this exact URL. A navigation should
    // land somewhere useful rather than on a browser error page, and with
    // no network the only useful place is the downloads the device
    // already holds.
    if (request.mode === "navigate") {
      return (await caches.match("/downloads")) || (await caches.match("/login")) ||
        new Response("Offline", { status: 503, headers: { "Content-Type": "text/plain" } });
    }
    return new Response("Offline", { status: 503 });
  }

  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response.ok) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
          return response;
        }
        // The server being down does not look like being offline: the tunnel
        // still answers, with Cloudflare's own 502/530 page. For a page
        // load that is the same situation, so it gets the same fallback.
        // Gateway codes only: a 500 is the site's own error, worth seeing.
        const s = response.status;
        if (request.mode === "navigate" && (s === 502 || s === 503 || s === 504 || s >= 520)) return fallback();
        return response;
      })
      .catch(fallback),
  );
});

// The page asks for this when a download starts — the moment somebody has
// declared they intend to be offline. Re-fetching the shell then means the
// downloads screen is definitely cached before it is needed, rather than
// only if they happened to visit it earlier.
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "warm") {
    event.waitUntil(
      caches.open(CACHE_NAME).then((cache) =>
        cache
          .addAll(PRECACHE_URLS)
          .then(() => cacheStatic(cache))
          .catch(() => {
            // Warming is best effort; failing it must not break the download
            // that triggered it.
          }),
      ),
    );
  }
});
`;
}

export function GET(): Response {
  return new Response(serviceWorkerSource(BUILD_ID, STATIC_URLS), {
    headers: {
      "Content-Type": "text/javascript; charset=utf-8",
      // Lets the worker control the whole origin even though it is served
      // from /sw.js.
      "Service-Worker-Allowed": "/",
      // The browser must notice a new worker promptly; this is the file whose
      // bytes changing is what triggers an update at all.
      "Cache-Control": "no-cache, no-store, must-revalidate",
    },
  });
}
